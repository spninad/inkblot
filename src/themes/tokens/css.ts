import type { LanguageTokens, Mode, ShadowLayer, TypeRole } from './types'
import { LANGUAGE_IDS, MODES } from './types'
import { languages } from './languages'

const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`
export const shadowToCss = (layers: ShadowLayer[]) =>
  layers.length ? layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${l.color}`).join(', ') : 'none'

function typeVars(name: string, r: TypeRole): string[] {
  const p = `--dl-type-${name}`
  return [
    `${p}-family: var(--dl-font-${r.font});`,
    `${p}-size: ${rem(r.size)};`,
    `${p}-line: ${rem(r.line)};`,
    `${p}-weight: ${r.weight};`,
    `${p}-tracking: ${r.tracking}em;`,
  ]
}

/** Variables that do not change with colour mode. */
function staticVars(t: LanguageTokens): string[] {
  const v: string[] = []
  ;(['sans', 'display', 'serif', 'mono', 'hand'] as const).forEach((k) => v.push(`--dl-font-${k}: ${t.fonts[k].stack};`))
  Object.entries(t.type).forEach(([k, r]) => v.push(...typeVars(k, r)))
  t.space.forEach((s, i) => v.push(`--dl-space-${i}: ${rem(s)};`))
  ;(['sm', 'md', 'lg'] as const).forEach((k) => v.push(`--dl-control-${k}: ${rem(t.control[k])};`))
  Object.entries(t.radius).forEach(([k, r]) => v.push(`--dl-radius-${k}: ${r}px;`))
  Object.entries(t.border).forEach(([k, r]) => v.push(`--dl-border-${k}: ${r}px;`))
  v.push(`--dl-focus-width: ${t.focus.width}px;`, `--dl-focus-offset: ${t.focus.offset}px;`)
  v.push(`--dl-dur-fast: ${t.motion.fast}ms;`, `--dl-dur-base: ${t.motion.base}ms;`, `--dl-dur-slow: ${t.motion.slow}ms;`)
  v.push(`--dl-ease: ${t.motion.ease};`, `--dl-ease-enter: ${t.motion.enter};`, `--dl-ease-exit: ${t.motion.exit};`, `--dl-ease-spring: ${t.motion.spring};`)
  v.push(`--dl-icon-stroke: ${t.icon.stroke};`)
  return v
}

function modeVars(t: LanguageTokens, mode: Mode): string[] {
  const c = t.colors[mode]
  const v: string[] = []
  const simple = ['bg', 'surface', 'raised', 'sunken', 'scrim', 'border', 'controlBorder', 'borderStrong', 'text', 'muted', 'primary', 'onPrimary', 'primaryHover', 'focus', 'selection'] as const
  const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
  simple.forEach((k) => v.push(`--dl-${kebab(k)}: ${c[k]};`))
  const emitTone = (name: string, tn: { solid: string; on: string; tint: string; ink: string }) =>
    v.push(`--dl-${name}: ${tn.solid};`, `--dl-${name}-on: ${tn.on};`, `--dl-${name}-tint: ${tn.tint};`, `--dl-${name}-ink: ${tn.ink};`)
  Object.entries(c.tones).forEach(([k, tn]) => emitTone(k, tn))
  Object.entries(c.categories).forEach(([k, tn]) => emitTone(k, tn))
  ;([0, 1, 2, 3] as const).forEach((i) => v.push(`--dl-shadow-${i}: ${shadowToCss(t.elevation[mode][i])};`))
  v.push(`color-scheme: ${mode};`)
  return v
}

/**
 * Emits one CSS file. Scoped to `[data-language][data-mode]` on a container (not :root), so several
 * languages can be rendered side by side on one page.
 */
export function buildCss(): string {
  const out: string[] = ['/* GENERATED by packages/tokens/scripts/build-css.ts — do not edit. */']
  for (const id of LANGUAGE_IDS) {
    const t = languages[id]
    out.push(`[data-language="${id}"] {\n  ${staticVars(t).join('\n  ')}\n}`)
    for (const mode of MODES) {
      out.push(`[data-language="${id}"][data-mode="${mode}"] {\n  ${modeVars(t, mode).join('\n  ')}\n}`)
    }
    // System mode uses media queries, so its first paint matches the OS even
    // before a React provider hydrates.
    out.push(`[data-language="${id}"][data-mode="system"] {\n  ${modeVars(t, 'light').join('\n  ')}\n}`)
    out.push(`@media (prefers-color-scheme: dark) {\n  [data-language="${id}"][data-mode="system"] {\n    ${modeVars(t, 'dark').join('\n    ')}\n  }\n}`)
  }
  return out.join('\n\n') + '\n'
}
